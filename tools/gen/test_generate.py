#!/usr/bin/env python3
"""Unit tests of tools/gen/generate.py. Run: python -m unittest tools/gen/test_generate.py"""
import contextlib
import io
import sys
import tempfile
import unittest
from pathlib import Path

GEN_DIR = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(GEN_DIR))
import generate as g  # noqa: E402

FAKE = '''
NAME = "{name}"
def generate(root):
    return {outputs}
'''
HEADER = "// Generated by tools/gen/gen_x.py from x.def - do not edit\\n"


_TMP_DIRS: list[tempfile.TemporaryDirectory] = []


def run_gen(gens: dict[str, str], files: dict[str, str], *args: str) -> tuple[int, str, Path]:
    tmp = tempfile.TemporaryDirectory()
    _TMP_DIRS.append(tmp)
    root = Path(tmp.name)
    gen_dir = root / "tools" / "gen"
    gen_dir.mkdir(parents=True)
    for name, source in gens.items():
        (gen_dir / f"gen_{name}.py").write_text(source, encoding="utf-8")
    for rel, content in files.items():
        (root / rel).parent.mkdir(parents=True, exist_ok=True)
        (root / rel).write_text(content, encoding="utf-8")
    out = io.StringIO()
    with contextlib.redirect_stdout(out):
        code = g.main(["--root", str(root), "--gen-dir", str(gen_dir), *args])
    return code, out.getvalue(), root


def fake(name: str, outputs: str) -> str:
    return FAKE.format(name=name, outputs=outputs)


class Generate(unittest.TestCase):
    def tearDown(self):
        while _TMP_DIRS:
            _TMP_DIRS.pop().cleanup()

    def test_no_generators_succeeds(self):
        self.assertEqual(run_gen({}, {})[0], 0)
        self.assertEqual(run_gen({}, {}, "--check")[0], 0)

    def test_real_generators_are_up_to_date(self):
        with contextlib.redirect_stdout(io.StringIO()):
            self.assertEqual(g.main(["--check"]), 0)

    def test_writes_files(self):
        gen = fake("x", f'{{"src-next/a/out.spice": "{HEADER}body\\n"}}')
        code, out, root = run_gen({"x": gen}, {})
        self.assertEqual(code, 0)
        self.assertEqual((root / "src-next/a/out.spice").read_text(), HEADER.replace("\\n", "\n") + "body\n")
        self.assertIn("generated src-next/a/out.spice", out)

    def test_check_passes_when_up_to_date(self):
        gen = fake("x", f'{{"src-next/out.spice": "{HEADER}"}}')
        code, out, _ = run_gen({"x": gen}, {"src-next/out.spice": HEADER.replace("\\n", "\n")}, "--check")
        self.assertEqual(code, 0, out)

    def test_check_fails_on_difference_or_missing_and_writes_nothing(self):
        gen = fake("x", f'{{"src-next/out.spice": "{HEADER}", "src-next/new.spice": "{HEADER}"}}')
        code, out, root = run_gen({"x": gen}, {"src-next/out.spice": "// stale\n"}, "--check")
        self.assertEqual(code, 1)
        self.assertIn("src-next/out.spice", out)
        self.assertIn("src-next/new.spice (missing)", out)
        self.assertEqual((root / "src-next/out.spice").read_text(), "// stale\n")
        self.assertFalse((root / "src-next/new.spice").exists())

    def test_rejects_output_outside_src_next(self):
        for bad in ("std/out.spice", "src-next/../std/out.spice"):
            gen = fake("x", f'{{"{bad}": "{HEADER}"}}')
            with self.assertRaises(SystemExit):
                run_gen({"x": gen}, {})

    def test_rejects_missing_header_and_duplicate_outputs(self):
        with self.assertRaises(SystemExit):
            run_gen({"x": fake("x", '{"src-next/o.spice": "body\\n"}')}, {})
        same = f'{{"src-next/o.spice": "{HEADER}"}}'
        with self.assertRaises(SystemExit):
            run_gen({"x": fake("x", same), "y": fake("y", same)}, {})

    def test_rejects_incomplete_or_duplicate_generator(self):
        with self.assertRaises(SystemExit):
            run_gen({"x": "NAME = 'x'\n"}, {})
        with self.assertRaises(SystemExit):
            run_gen({"x": fake("n", "{}"), "y": fake("n", "{}")}, {})

    def test_only_selects_generators(self):
        gx = fake("x", f'{{"src-next/x.spice": "{HEADER}"}}')
        gy = fake("y", f'{{"src-next/y.spice": "{HEADER}"}}')
        _, _, root = run_gen({"x": gx, "y": gy}, {}, "--only", "x")
        self.assertTrue((root / "src-next/x.spice").exists())
        self.assertFalse((root / "src-next/y.spice").exists())
        with self.assertRaises(SystemExit):
            run_gen({"x": gx}, {}, "--only", "nope")


if __name__ == "__main__":
    unittest.main()
