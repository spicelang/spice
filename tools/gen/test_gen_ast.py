#!/usr/bin/env python3
"""Unit tests of tools/gen/gen_ast.py. Run: python -m unittest tools/gen/test_gen_ast.py"""
import re
import sys
import tempfile
import unittest
from pathlib import Path

GEN_DIR = Path(__file__).resolve().parent
REPO_ROOT = GEN_DIR.parent.parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(GEN_DIR))
import gen_ast as gen  # noqa: E402

GOOD = """# comment
import "@/source/span"
enum Op: OP_A OP_B
node FIRST misc
  child inner?: SECOND_KIND
  list items: SECOND_KIND|FIRST
  field op: Op
  field flag: bool
  field count: int = 1
node SECOND_KIND stmt
"""


def generate(definition: str) -> dict[str, str]:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / gen.DEF_PATH
        path.parent.mkdir(parents=True)
        path.write_text(definition, encoding="utf-8")
        return gen.generate(Path(tmp))


def rejects(definition: str, fragment: str) -> bool:
    try:
        gen.parse(definition)
    except SystemExit as e:
        return fragment in str(e)
    return False


class GenAstTest(unittest.TestCase):
    def test_real_definition_has_the_legacy_kinds_in_legacy_order(self):
        d = gen.parse((REPO_ROOT / gen.DEF_PATH).read_text(encoding="utf-8"))
        legacy = (REPO_ROOT / "src/ast/ast-nodes.spice").read_text(encoding="utf-8")
        body = re.search(r"public type ASTNodeKind enum \{(.*?)\}", legacy, re.S).group(1)
        kinds = [k.strip() for k in body.split(",") if k.strip() and k.strip() != "INVALID"]
        self.assertEqual(78, len(kinds))
        self.assertEqual(kinds, [n.kind for n in d.nodes])

    def test_real_definition_generates_every_file_with_the_header(self):
        files = gen.generate(REPO_ROOT)
        self.assertEqual(10, len(files))
        for path, content in files.items():
            self.assertTrue(path.startswith("src-next/syntax/ast/"))
            self.assertTrue(content.startswith("// Generated by tools/gen/gen_ast.py"), path)

    def test_names_are_derived_from_the_kinds(self):
        self.assertEqual("TopLevelDefAttr", gen.camel("TOP_LEVEL_DEF_ATTR"))
        self.assertEqual("FctDef", gen.camel("FCT_DEF"))

    def test_generates_struct_ctor_store_and_visitor(self):
        files = generate(GOOD)
        nodes = files["src-next/syntax/ast/nodes-misc.spice"]
        self.assertIn("public type FirstNode struct {", nodes)
        self.assertIn("public NodeId inner // SECOND_KIND (optional)", nodes)
        self.assertIn("public ChildRange items // SECOND_KIND or FIRST", nodes)
        self.assertIn("this.op = Op::OP_A;", nodes)
        self.assertIn("this.count = 1;", gen.emit_nodes(gen.parse(GOOD), "misc"))
        self.assertIn("this.inner = noNodeId();", nodes)
        self.assertIn("public f<NodeId> AstStore.addSecondKind(", files["src-next/syntax/ast/ast-store.spice"])
        self.assertIn("pushChildRange(store, out, node.items);", files["src-next/syntax/ast/ast-children.spice"])
        self.assertIn("public p IAstVisitor.visitSecondKind(NodeId id) {", files["src-next/syntax/ast/ast-visitor.spice"])
        self.assertIn('"SecondKindNode"', files["src-next/syntax/ast/ast-enums.spice"])

    def test_children_keep_the_order_of_the_definition(self):
        children = generate(GOOD)["src-next/syntax/ast/ast-children.spice"]
        self.assertLess(children.index("node.inner"), children.index("node.items"))

    def test_rejects_malformed_definitions(self):
        self.assertTrue(rejects("node A misc\nnode A misc\n", "defined twice"))
        self.assertTrue(rejects("node A nowhere\n", "unknown group"))
        self.assertTrue(rejects("  field x: bool\n", "before the first node"))
        self.assertTrue(rejects("node A misc\n  child c: B\n", "unknown kind"))
        self.assertTrue(rejects("node A misc\n  field c: Unknown\n", "unsupported type"))
        self.assertTrue(rejects("node A misc\n  field type: bool\n", "malformed member"))
        self.assertTrue(rejects("node A misc\n  list x?: A\n", "only a child can be optional"))
        self.assertTrue(rejects("node A misc\n  field x: bool\n  field x: bool\n", "defined twice"))
        self.assertTrue(rejects("enum E: a\n", "malformed enum"))
        self.assertTrue(rejects("frobnicate\n", "unknown directive"))


if __name__ == "__main__":
    unittest.main()
