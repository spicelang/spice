#!/usr/bin/env python3
"""Runs the code generators of the compiler re-implementation (media/specs/compiler-reimplementation.md, section 6.6).

A generator is a module in tools/gen/ named `gen_<name>.py`. It has this interface:

    NAME: str                                      # the name for --only and the messages, e.g. "ast"
    def generate(root: Path) -> dict[str, str]     # relative output path (below the repository root) -> file content

The generators read their declarative definition (e.g. `src-next/syntax/ast/ast.def`) below the repository root and return
the complete content of every file they produce. The content of each generated file starts with the header from
`header()`, so that it is recognizable as generated. The generated files are committed, so the stage0 build needs no
extra step.

Without arguments, the files are (re)written. With --check, nothing is written. The run fails (exit code 1) if a generated
file is missing or differs from the committed one, so that CI notices a forgotten regeneration. With no generator
present (phase 0), both modes succeed.

Examples:
  python tools/gen/generate.py            # regenerate everything
  python tools/gen/generate.py --check    # CI: are the committed files up to date?
  python tools/gen/generate.py --only ast
"""
from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path
from types import ModuleType

sys.dont_write_bytecode = True

GEN_DIR = Path(__file__).resolve().parent
REPO_ROOT = GEN_DIR.parent.parent
GENERATED_ROOT = "src-next"


def header(generator: str, source: str) -> str:
    """The first lines of every generated Spice file. `generator` is the path of the generator, `source` the definition."""
    return f"// Generated by {generator} from {source} - do not edit\n"


def load_generators(gen_dir: Path = GEN_DIR) -> list[ModuleType]:
    """Loads all `gen_*.py` modules of a directory, sorted by file name, and validates their interface."""
    modules = []
    for path in sorted(gen_dir.glob("gen_*.py")):
        spec = importlib.util.spec_from_file_location(path.stem, path)
        assert spec is not None and spec.loader is not None
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        for attr in ("NAME", "generate"):
            if not hasattr(module, attr):
                raise SystemExit(f"error: {path.name} has no '{attr}'")
        modules.append(module)
    names = [m.NAME for m in modules]
    for name in sorted({n for n in names if names.count(n) > 1}):
        raise SystemExit(f"error: generator name '{name}' is used twice")
    return modules


def collect_outputs(modules: list[ModuleType], root: Path) -> dict[str, str]:
    """Runs the generators. Every output has to be below src-next/ and may be produced by one generator only."""
    outputs: dict[str, str] = {}
    owners: dict[str, str] = {}
    for module in modules:
        for rel, content in module.generate(root).items():
            rel = Path(rel).as_posix()
            if not rel.startswith(GENERATED_ROOT + "/") or ".." in rel.split("/"):
                raise SystemExit(f"error: generator '{module.NAME}' writes outside of {GENERATED_ROOT}/: {rel}")
            if rel in outputs:
                raise SystemExit(f"error: '{rel}' is generated by '{owners[rel]}' and '{module.NAME}'")
            if "do not edit" not in content.split("\n", 1)[0]:
                raise SystemExit(f"error: the output '{rel}' of '{module.NAME}' has no generated header")
            outputs[rel] = content
            owners[rel] = module.NAME
    return outputs


def run(root: Path, modules: list[ModuleType], check: bool) -> int:
    outputs = collect_outputs(modules, root)
    stale = []
    for rel, content in outputs.items():
        path = root / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        if check:
            stale.append(rel + (" (missing)" if current is None else ""))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"generated {rel}")
    if stale:
        print("Generated files are out of date, run 'python tools/gen/generate.py':")
        for rel in stale:
            print(f"  {rel}")
        return 1
    if check:
        print(f"{len(outputs)} generated file(s) up to date")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the code generators of src-next")
    parser.add_argument("--check", action="store_true", help="do not write, fail if a generated file is out of date")
    parser.add_argument("--only", action="append", metavar="NAME", help="run only this generator (repeatable)")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="repository root (default: this repository)")
    parser.add_argument("--gen-dir", type=Path, default=GEN_DIR, help="directory with the gen_*.py modules")
    args = parser.parse_args(argv)

    modules = load_generators(args.gen_dir)
    if args.only:
        unknown = set(args.only) - {m.NAME for m in modules}
        if unknown:
            parser.error(f"unknown generator(s): {', '.join(sorted(unknown))}")
        modules = [m for m in modules if m.NAME in args.only]
    return run(args.root, modules, args.check)


if __name__ == "__main__":
    sys.exit(main())
