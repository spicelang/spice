#!/usr/bin/env python3
"""Compile the code examples of the documentation with the Spice compiler.

Every ``spice`` code block in ``docs/docs/**/*.md``, that is a complete program (contains ``f<int> main(``), has to
compile. Code blocks without a main function are fragments and are not compiled. A marker comment in front of a code
block changes, what is expected of it:

- ``<!-- doc-test: skip <reason> -->``: don't compile the code block, e.g. because it continues an earlier snippet or
  imports a source file of another code block.
- ``<!-- doc-test: expect-error <message> -->``: the compilation has to fail, with an output that contains the message,
  e.g. because the code block demonstrates a compile error.

Problems are reported as ``<md file>:<line>: <message>``, at the line of the compile error in the md file, and as
annotations on GitHub Actions.

Usage:
    python tools/check_doc_examples.py [--compiler build/spice] [--jobs N] [<md file>...]
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
DOCS_DIR = ROOT_DIR / "docs" / "docs"
# Generated by tools/generate_std_docs.py, not part of the sources
GENERATED_DOCS_DIR = DOCS_DIR / "std"
EXE_SUFFIX = ".exe" if os.name == "nt" else ""
COMPILE_TIMEOUT = 300  # Seconds

FENCE_START = re.compile(r"^(?P<indent>\s*)```(?P<lang>[^\s`]*).*$")
MARKER = re.compile(r"^\s*<!--\s*doc-test:\s*(?P<directive>[\w-]+)(?P<argument>.*?)-->\s*$")
DIRECTIVES = {"skip", "expect-error"}
# Location of a diagnostic in the compiled source file, e.g. './example.spice:3:5:'
SOURCE_LOCATION = re.compile(r"\./example\.spice:(?P<line>\d+):\d+")
ANSI_ESCAPE = re.compile(r"\x1b\[[0-9;]*m")


@dataclass
class Example:
    md_file: Path
    line: int  # Line of the opening fence in the md file
    code: str
    directive: str | None = None
    argument: str = ""

    @property
    def location(self) -> str:
        return f"{display_path(self.md_file)}:{self.line}"


@dataclass
class Problem:
    location: str  # <md file>:<line>
    message: str


def display_path(path: Path) -> str:
    try:
        return path.resolve().relative_to(ROOT_DIR).as_posix()
    except ValueError:
        return str(path)


def parse_md_file(md_file: Path, problems: list[Problem]) -> list[Example]:
    """
    Collect the spice code blocks with a main function of the md file, together with the marker in front of them

    :return: The examples to compile
    """
    md_path = display_path(md_file)
    lines = md_file.read_text(encoding="utf-8").splitlines()
    examples: list[Example] = []
    marker: tuple[int, str, str] | None = None  # Line, directive and argument of the marker in front of the next code block
    i = 0
    while i < len(lines):
        line = lines[i]
        if match := MARKER.match(line):
            if marker:
                problems.append(Problem(f"{md_path}:{marker[0]}", "Marker is not followed by a spice code block"))
            directive, argument = match["directive"], match["argument"].strip()
            if directive not in DIRECTIVES:
                expected = ", ".join(sorted(DIRECTIVES))
                problems.append(Problem(f"{md_path}:{i + 1}",
                                        f"Unknown doc-test directive '{directive}', expected one of: {expected}"))
            elif not argument:
                expected = "a reason" if directive == "skip" else "the expected error message"
                problems.append(Problem(f"{md_path}:{i + 1}", f"The doc-test marker '{directive}' needs {expected}"))
            else:
                marker = (i + 1, directive, argument)
            i += 1
        elif match := FENCE_START.match(line):
            # Collect the code block up to the closing fence with the same indentation
            indent = match["indent"]
            fence_line = i + 1
            i += 1
            code_lines = []
            while i < len(lines) and lines[i].rstrip() != f"{indent}```":
                code_lines.append(lines[i][len(indent):] if lines[i].startswith(indent) else lines[i].lstrip())
                i += 1
            i += 1  # Closing fence
            code = "\n".join(code_lines) + "\n"
            is_program = match["lang"] == "spice" and "f<int> main(" in code
            if is_program:
                example = Example(md_file, fence_line, code)
                if marker:
                    example.directive, example.argument = marker[1], marker[2]
                examples.append(example)
            elif marker:
                problems.append(Problem(f"{md_path}:{marker[0]}",
                                        "Marker is not followed by a spice code block with a main function"))
            marker = None
        else:
            if marker and line.strip():
                problems.append(Problem(f"{md_path}:{marker[0]}", "Marker is not followed by a spice code block"))
                marker = None
            i += 1
    if marker:
        problems.append(Problem(f"{md_path}:{marker[0]}", "Marker is not followed by a spice code block"))
    return examples


def first_error(output: str, example: Example) -> Problem:
    """Extract the first diagnostic of the compiler output, located at the line of the error in the md file"""
    lines = output.splitlines()
    # Diagnostics start with '[Error|...]' and continue in the next line. The summary of the soft errors is skipped
    starts = [i for i, line in enumerate(lines) if line.startswith("[Error|") and not line.startswith("[Error|Compiler]")]
    starts = starts or [i for i, line in enumerate(lines) if line.startswith("[Error|")]
    if not starts:
        return Problem(example.location, "\n".join(lines[-5:]) or "Compilation failed without output")
    message = " ".join(line.strip() for line in lines[starts[0]:starts[0] + 2] if line.strip())
    # '[Error|Semantic] ./example.spice:3:5: <message>' -> '<md file>:<fence line + 3>: [Error|Semantic] <message>'
    if match := SOURCE_LOCATION.search(message):
        location = f"{display_path(example.md_file)}:{example.line + int(match['line'])}"
        return Problem(location, message[:match.start()] + message[match.end():].removeprefix(":").lstrip())
    return Problem(example.location, message)


def check_example(compiler: Path, work_dir: Path, index: int, example: Example) -> Problem | None:
    """
    Compile the example and check the result against the expectation of its marker

    :return: The problem, if the example does not behave as expected
    """
    # Each example gets its own dir, so that the examples can't see each other's files
    example_dir = work_dir / str(index)
    example_dir.mkdir()
    (example_dir / "example.spice").write_text(example.code, encoding="utf-8")
    cmd = [str(compiler), "build", "-O0", "example.spice", "-o", f"example{EXE_SUFFIX}"]
    try:
        result = subprocess.run(cmd, cwd=example_dir, stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
                                stderr=subprocess.STDOUT, encoding="utf-8", errors="replace", timeout=COMPILE_TIMEOUT)
    except subprocess.TimeoutExpired:
        return Problem(example.location, f"Compilation timed out after {COMPILE_TIMEOUT}s")
    output = ANSI_ESCAPE.sub("", result.stdout)

    if example.directive == "expect-error":
        if result.returncode == 0:
            return Problem(example.location, f"Compiled, but an error was expected: {example.argument}")
        if example.argument not in output:
            error = first_error(output, example)
            return Problem(error.location, f"Failed with another error than expected ({example.argument}): {error.message}")
        return None
    if result.returncode != 0:
        return first_error(output, example)
    return None


def report(problem: Problem) -> None:
    print(f"{problem.location}: {problem.message}")
    if os.environ.get("GITHUB_ACTIONS") == "true":
        file, line = problem.location.rsplit(":", 1)
        # Escaping of workflow command values
        message = problem.message.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
        print(f"::error file={file},line={line}::{message}")


def main() -> int:
    parser = argparse.ArgumentParser(description="Compile the code examples of the documentation with the Spice compiler.")
    parser.add_argument("md_files", nargs="*", type=Path,
                        help="md files to check (default: all md files in docs/docs, except the generated std reference)")
    parser.add_argument("--compiler", type=Path, default=ROOT_DIR / "build" / f"spice{EXE_SUFFIX}",
                        help="Compiler to compile the examples with (default: build/spice)")
    parser.add_argument("-j", "--jobs", type=int, default=os.cpu_count() or 1,
                        help="Number of examples to compile in parallel (default: number of CPUs)")
    args = parser.parse_args()

    compiler = args.compiler.resolve()
    if not compiler.is_file():
        print(f"Compiler not found: {compiler}. Build it with 'python build.py' or pass --compiler", file=sys.stderr)
        return 2
    md_files = args.md_files or sorted(f for f in DOCS_DIR.rglob("*.md") if GENERATED_DOCS_DIR not in f.parents)
    # Compile against the std of this checkout
    os.environ["SPICE_STD_DIR"] = str(ROOT_DIR / "std")

    problems: list[Problem] = []
    examples = [example for md_file in md_files for example in parse_md_file(md_file, problems)]
    to_compile = [example for example in examples if example.directive != "skip"]
    with tempfile.TemporaryDirectory(prefix="spice-doc-examples-") as work_dir:
        with ThreadPoolExecutor(max_workers=max(args.jobs, 1)) as executor:
            results = executor.map(lambda item: check_example(compiler, Path(work_dir), *item), enumerate(to_compile))
            problems += [problem for problem in results if problem]

    for problem in problems:
        report(problem)
    skipped = len(examples) - len(to_compile)
    print(f"Checked {len(to_compile)} examples in {len(md_files)} md files ({skipped} skipped): {len(problems)} problems")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
