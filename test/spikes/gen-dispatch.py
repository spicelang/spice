#!/usr/bin/env python3
"""Generates dispatch.spice (spike 6 of media/specs/compiler-reimplementation.md, section 7.3).

78 node kinds are evaluated through (a) a `switch` over a kind enum and (b) an interface implemented by 78 structs.
Run: python test/spikes/gen-dispatch.py > test/spikes/dispatch.spice
"""
N = 78

print("""// Generated by test/spikes/gen-dispatch.py - do not edit
// Spike 6: performance of 'switch' dispatch vs. interface dispatch on 78 kinds.
// Run it as a release build, e.g. 'spice build -O2 test/spikes/dispatch.spice', it prints the times.
import "std/time/time";
""")
print("type Kind enum {")
print(",\n".join(f"    K{i}" for i in range(N)))
print("}\n")
print("""type INode interface {
    f<long> eval(long);
}
""")
for i in range(N):
    print(f"type S{i} struct : INode {{\n    long salt\n}}\n")
    print(f"f<long> S{i}.eval(long x) {{\n    return x * {i + 3}l + this.salt;\n}}\n")
print("f<long> evalSwitch(Kind kind, long x, long salt) {\n    switch kind {")
for i in range(N):
    print(f"        case Kind::K{i}: {{ return x * {i + 3}l + salt; }}")
print("        default: { panic(Error(1, \"unknown kind\")); }\n    }\n}\n")
print("const unsigned int COUNT = 4096u;\n")
print("// Pseudo random kinds, so that the branch predictor has no pattern to learn\nf<unsigned int> nextKind(unsigned long& state) {\n    state = state * 6364136223846793005ul + 1442695040888963407ul;\n    return cast<unsigned int>((state >> 33ul) % 78ul);\n}\n")
print("""f<long> switchLoop(long rounds) {
    unsigned long state = 42ul;
    Kind[4096] kinds;
    for unsigned int i = 0u; i < COUNT; i++ {
        kinds[i] = cast<Kind>(nextKind(state));
    }
    long acc = 0l;
    for long r = 0l; r < rounds; r++ {
        for unsigned int i = 0u; i < COUNT; i++ {
            acc += evalSwitch(kinds[i], acc & 255l, 1l);
        }
    }
    return acc;
}
""")
print("f<long> interfaceLoop(long rounds) {")
for i in range(N):
    print(f"    S{i} s{i};\n    s{i}.salt = 1l;")
print("    INode*[78] table;")
for i in range(N):
    print(f"    table[{i}] = &s{i};")
print("""    unsigned long state = 42ul;
    INode*[4096] nodes;
    for unsigned int i = 0u; i < COUNT; i++ {
        nodes[i] = table[nextKind(state)];
    }
    long acc = 0l;
    for long r = 0l; r < rounds; r++ {
        for unsigned int i = 0u; i < COUNT; i++ {
            acc += nodes[i].eval(acc & 255l);
        }
    }
    return acc;
}
""")
print("""#[test]
f<bool> testSwitchAndInterfaceAgree() {
    return switchLoop(3l) == interfaceLoop(3l);
}

f<int> main() {
    const long rounds = 100000l;
    const long t0 = getCurrentMillis();
    const long a = switchLoop(rounds);
    const long t1 = getCurrentMillis();
    const long b = interfaceLoop(rounds);
    const long t2 = getCurrentMillis();
    printf("switch:    %ld ms (result %ld)\\n", t1 - t0, a);
    printf("interface: %ld ms (result %ld)\\n", t2 - t1, b);
    return a == b ? 0 : 1;
}""")
